#!/usr/bin/env python3
"""Write catalog.toml (the index Noctalia reads from a git plugin source) from
each plugin folder's plugin.toml. Run from the repository root after changing
a plugin, and commit the result."""
import os, subprocess, sys, time, tomllib

FIELDS = ["id", "name", "version", "updated_at", "added_at", "author", "license",
          "icon", "description", "plugin_api", "tags"]


def first_commit_time(path):
    out = subprocess.run(["git", "log", "--diff-filter=A", "--format=%ct", "--", path],
                         capture_output=True, text=True).stdout.split()
    return int(out[-1]) if out else int(time.time())


def last_commit_time(path):
    out = subprocess.run(["git", "log", "-1", "--format=%ct", "--", path],
                         capture_output=True, text=True).stdout.strip()
    return int(out) if out else int(time.time())


def fmt(v):
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, list):
        return "[" + ", ".join(fmt(x) for x in v) + "]"
    return str(v)


rows = []
for d in sorted(os.listdir(".")):
    manifest = os.path.join(d, "plugin.toml")
    if not os.path.isfile(manifest):
        continue
    with open(manifest, "rb") as f:
        m = tomllib.load(f)
    m["added_at"] = first_commit_time(manifest)
    m["updated_at"] = last_commit_time(manifest)
    rows.append("[[plugin]]\n" + "".join(f"{k} = {fmt(m[k])}\n" for k in FIELDS if k in m))

with open("catalog.toml", "w") as f:
    f.write("# Noctalia plugins catalog: one [[plugin]] row per plugin folder.\n"
            "# Generated by tools/make-catalog.py from each plugin.toml.\n\n")
    f.write("\n".join(rows))
print(f"catalog.toml: {len(rows)} plugin(s)", file=sys.stderr)
